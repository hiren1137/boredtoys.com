export interface Item {
  name: string;
  emoji: string;
}

export const STARTERS = ['Water', 'Fire', 'Earth', 'Wind'];

const items = new Map<string, Item>();
const recipes = new Map<string, string>();

/** Unordered pair key, so A+B and B+A find the same recipe. */
export const pairKey = (a: string, b: string) => (a < b ? `${a}+${b}` : `${b}+${a}`);

for (const raw of DATA.split('\n')) {
  const line = raw.trim();
  if (!line) continue;
  const [head, body] = line.split(' = ');
  const space = head.indexOf(' ');
  const emoji = head.slice(0, space);
  const name = head.slice(space + 1).trim();
  items.set(name, { name, emoji });
  if (!body) continue;
  for (const combo of body.split(';')) {
    const [a, b] = combo.split('+').map((p) => p.trim());
    recipes.set(pairKey(a, b), name);
  }
}

export const ITEMS = items;
export const RECIPES = recipes;
export const TOTAL_ITEMS = items.size;

export function combine(a: string, b: string): string | null {
  return recipes.get(pairKey(a, b)) ?? null;
}
